#!/usr/bin/env python3
"""Generates the desktop application's icon set from one geometric design.

The design (docs/design/visual.md, "Application icon"): a moss tile with a
paper-colored mark. Three tool calls arrive from the left at a gate; one
continues to the right. Flat colors, axis-aligned bars, no gradient, glow or
glyph. The same shapes are written as the SVG source and rasterized here
with exact area coverage, so the output is byte-for-byte reproducible on any
machine with Python 3 and no image library.

Usage:
    python3 -I desktop/scripts/make-icons.py           # write the files
    python3 -I desktop/scripts/make-icons.py --check   # exit 1 if any differs

Outputs, in desktop/src-tauri/icons/: app-icon.svg (the source),
32x32.png, 128x128.png, 128x128@2x.png, icon.png (512),
icon.icns (macOS) and icon.ico (Windows).
"""

import struct
import sys
import zlib
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src-tauri" / "icons"

# Tokens of docs/design/visual.md: --moss (light) for the tile, --paper for the mark.
TILE = (0x2C, 0x5A, 0x46)
MARK = (0xF4, 0xF5, 0xF0)

# Geometry on a 1024 canvas. The tile follows the macOS icon grid: an
# 824-unit body with 100 units of margin and a corner radius of 185.
TILE_BOX = (100, 100, 924, 924)
RADIUS = 185
# Mark: three incoming calls (bars that end at the gate), the gate (a
# vertical bar) and one outgoing call (the middle bar continues).
BAR = 64  # thickness of a call
ROWS = (352, 480, 608)  # top edge of each call
MARK_RECTS = [
    (250, ROWS[0], 520, ROWS[0] + BAR),
    (250, ROWS[1], 520, ROWS[1] + BAR),
    (250, ROWS[2], 520, ROWS[2] + BAR),
    (520, 300, 600, 724),  # the gate
    (600, ROWS[1], 774, ROWS[1] + BAR),
]


def svg() -> str:
    x0, y0, x1, y1 = TILE_BOX
    hexc = lambda c: "#%02x%02x%02x" % c  # noqa: E731
    rects = "\n".join(
        f'  <rect x="{a}" y="{b}" width="{c - a}" height="{d - b}"/>' for a, b, c, d in MARK_RECTS
    )
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">\n'
        "<!-- Secure MCP Gateway application icon. Generated by desktop/scripts/make-icons.py; edit the script, not this file. -->\n"
        f'<rect x="{x0}" y="{y0}" width="{x1 - x0}" height="{y1 - y0}" rx="{RADIUS}" fill="{hexc(TILE)}"/>\n'
        f'<g fill="{hexc(MARK)}">\n{rects}\n</g>\n'
        "</svg>\n"
    )


def rect_cover(px, py, s, r):
    """Area of the unit pixel (px, py) covered by rect r scaled by s."""
    x0, y0, x1, y1 = (v * s for v in r)
    w = min(px + 1, x1) - max(px, x0)
    h = min(py + 1, y1) - max(py, y0)
    return w * h if w > 0 and h > 0 else 0.0


def tile_cover(px, py, s):
    x0, y0, x1, y1 = (v * s for v in TILE_BOX)
    rad = RADIUS * s
    base = rect_cover(px, py, 1, (x0, y0, x1, y1))
    if base == 0:
        return 0.0
    # Corner regions: supersample against the quarter circles.
    near = lambda v, a, b: v + 1 > a and v < b  # noqa: E731
    in_corner = (near(px, x0, x0 + rad) or near(px, x1 - rad, x1)) and (near(py, y0, y0 + rad) or near(py, y1 - rad, y1))
    if not in_corner:
        return base
    n = 8
    hits = 0
    for sy in range(n):
        for sx in range(n):
            x = px + (sx + 0.5) / n
            y = py + (sy + 0.5) / n
            if not (x0 <= x <= x1 and y0 <= y <= y1):
                continue
            cx = min(max(x, x0 + rad), x1 - rad)
            cy = min(max(y, y0 + rad), y1 - rad)
            if (x - cx) ** 2 + (y - cy) ** 2 <= rad * rad:
                hits += 1
    return hits / (n * n)


def raster(size: int) -> bytes:
    s = size / 1024
    rows = []
    for py in range(size):
        row = bytearray([0])  # PNG filter type 0
        for px in range(size):
            t = tile_cover(px, py, s)
            m = min(1.0, sum(rect_cover(px, py, s, r) for r in MARK_RECTS))
            m = min(m, t)
            if t == 0:
                row += b"\0\0\0\0"
                continue
            # The mark sits on the tile: blend the two colors by the mark's
            # share of the covered area.
            f = m / t
            rgb = [round(TILE[i] * (1 - f) + MARK[i] * f) for i in range(3)]
            row += bytes(rgb + [round(t * 255)])
        rows.append(bytes(row))
    return png(size, size, b"".join(rows))


def png(w: int, h: int, raw: bytes) -> bytes:
    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def icns(pngs: dict) -> bytes:
    # PNG-encoded ICNS entries by pixel size (Apple "icns" types).
    types = [
        (b"icp4", 16), (b"icp5", 32), (b"ic07", 128), (b"ic08", 256), (b"ic09", 512), (b"ic10", 1024),
        (b"ic11", 32), (b"ic12", 64), (b"ic13", 256), (b"ic14", 512),
    ]
    body = b"".join(t + struct.pack(">I", len(pngs[n]) + 8) + pngs[n] for t, n in types)
    return b"icns" + struct.pack(">I", len(body) + 8) + body


def ico(pngs: dict) -> bytes:
    sizes = [16, 24, 32, 48, 64, 256]
    head = struct.pack("<HHH", 0, 1, len(sizes))
    offset = 6 + 16 * len(sizes)
    entries, data = b"", b""
    for n in sizes:
        b = pngs[n]
        entries += struct.pack("<BBBBHHII", n % 256, n % 256, 0, 0, 1, 32, len(b), offset + len(data))
        data += b
    return head + entries + data


def build() -> dict:
    pngs = {n: raster(n) for n in (16, 24, 32, 48, 64, 128, 256, 512, 1024)}
    return {
        "app-icon.svg": svg().encode(),
        "32x32.png": pngs[32],
        "128x128.png": pngs[128],
        "128x128@2x.png": pngs[256],
        "icon.png": pngs[512],
        "icon.icns": icns(pngs),
        "icon.ico": ico(pngs),
    }


def main() -> int:
    check = "--check" in sys.argv[1:]
    files = build()
    stale = []
    for name, data in files.items():
        p = OUT / name
        if check:
            if not p.exists() or p.read_bytes() != data:
                stale.append(name)
        else:
            p.write_bytes(data)
    if stale:
        print("make-icons: out of date, run python3 -I desktop/scripts/make-icons.py: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
